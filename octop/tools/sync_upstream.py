#!/usr/bin/env python3
"""Vendor upstream ponytail content into both Octop plugins (byte-identical).

Why vendoring: an Octop plugin directory is installed with ``shutil.copytree``
and must work without the rest of the fork checkout. We therefore ship a
**byte-identical copy** of the upstream files the adapter uses — never a patched
copy — and verify it with ``CHECKSUMS.sha256``.

Upstream files are read from this same repository root (the fork keeps upstream
trees untouched), so syncing needs no network access.

Usage::

    python3 octop/tools/sync_upstream.py            # write/refresh the copies
    python3 octop/tools/sync_upstream.py --check    # verify, exit 1 on drift
"""

from __future__ import annotations

import argparse
import hashlib
import re
import shutil
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
OCTOP_DIR = REPO_ROOT / "octop"
PLUGIN_DIRS = (OCTOP_DIR / "plugin",)
VENDOR_NAME = Path("_vendor") / "ponytail"

#: Upstream files the adapter actually reads. Everything is copied verbatim.
#: Upstream's own ``plugin.yaml`` is deliberately NOT vendored: an Octop plugin
#: ZIP must contain exactly one ``plugin.yaml`` (the plugin root's), and the
#: upstream version is recorded in ``UPSTREAM_VERSION`` instead.
COPY_FILES = ("__init__.py", "LICENSE")
COPY_DIRS = ("skills", "commands")


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def upstream_files() -> list[Path]:
    """Absolute paths of the upstream files to vendor, sorted for stable output."""
    files: list[Path] = []
    for name in COPY_FILES:
        candidate = REPO_ROOT / name
        if candidate.is_file():
            files.append(candidate)
    for name in COPY_DIRS:
        root = REPO_ROOT / name
        if root.is_dir():
            files.extend(path for path in root.rglob("*") if path.is_file())
    return sorted(files)


def manifest_for(vendor_root: Path) -> str:
    """Render ``CHECKSUMS.sha256`` for every file under ``vendor_root``."""
    lines = []
    for path in sorted(p for p in vendor_root.rglob("*") if p.is_file()):
        if path.name == "CHECKSUMS.sha256":
            continue
        lines.append(f"{sha256(path)}  {path.relative_to(vendor_root).as_posix()}")
    return "\n".join(lines) + "\n"


def sync(plugin_dir: Path, commit: str | None = None) -> Path:
    vendor_root = plugin_dir / VENDOR_NAME
    if vendor_root.exists():
        shutil.rmtree(vendor_root)
    vendor_root.mkdir(parents=True)
    for source in upstream_files():
        relative = source.relative_to(REPO_ROOT)
        destination = vendor_root / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, destination)
    meta = upstream_meta(commit)
    (vendor_root / "UPSTREAM_VERSION").write_text(
        f"version: {meta['version']}\ncommit: {meta['commit']}\n", encoding="utf-8"
    )
    (vendor_root / "CHECKSUMS.sha256").write_text(manifest_for(vendor_root), encoding="utf-8")
    return vendor_root


def check(plugin_dir: Path) -> list[str]:
    """Return a list of drift problems for one plugin's vendored copy."""
    vendor_root = plugin_dir / VENDOR_NAME
    problems: list[str] = []
    if not (vendor_root / "__init__.py").is_file():
        return [f"{plugin_dir.name}: vendored copy missing"]
    expected = {source.relative_to(REPO_ROOT).as_posix(): sha256(source) for source in upstream_files()}
    actual = {
        path.relative_to(vendor_root).as_posix(): sha256(path)
        for path in vendor_root.rglob("*")
        if path.is_file() and path.name != "CHECKSUMS.sha256"
    }
    for relative, digest in sorted(expected.items()):
        if relative not in actual:
            problems.append(f"{plugin_dir.name}: missing {relative}")
        elif actual[relative] != digest:
            problems.append(f"{plugin_dir.name}: stale {relative} (upstream changed)")
    expected["UPSTREAM_VERSION"] = None  # generated by this script
    for relative in sorted(set(actual) - set(expected)):
        problems.append(f"{plugin_dir.name}: extra {relative}")
    manifest = vendor_root / "CHECKSUMS.sha256"
    if not manifest.is_file():
        problems.append(f"{plugin_dir.name}: CHECKSUMS.sha256 missing")
    elif manifest.read_text(encoding="utf-8") != manifest_for(vendor_root):
        problems.append(f"{plugin_dir.name}: CHECKSUMS.sha256 out of date")
    return problems


def pinned_constant() -> str:
    """``PINNED_COMMIT`` shipped in the plugin runtime — the single source of truth."""
    runtime = OCTOP_DIR / "plugin" / "ponytail_runtime.py"
    match = re.search(r'PINNED_COMMIT = "([0-9a-f]+)"', runtime.read_text(encoding="utf-8"))
    return match.group(1) if match else "unknown"


def upstream_meta(commit: str | None = None) -> dict[str, str]:
    """Upstream version (from root ``plugin.yaml``) and the recorded sync commit.

    The commit is **not** derived from this fork's HEAD: our own commits only add
    ``octop/``, so HEAD would point at adapter work, not upstream. Pass
    ``--commit`` when syncing a new upstream release; otherwise the value in
    ``ponytail_runtime.PINNED_COMMIT`` is reused (and the consistency test fails
    if the two drift apart).
    """
    meta = {"commit": (commit or pinned_constant()).strip() or "unknown", "version": "unknown"}
    manifest = REPO_ROOT / "plugin.yaml"
    if manifest.is_file():
        for line in manifest.read_text(encoding="utf-8").splitlines():
            if line.startswith("version:"):
                meta["version"] = line.split(":", 1)[1].strip()
                break
    return meta


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify without writing")
    parser.add_argument(
        "--commit",
        default=None,
        help="upstream commit to record (default: PINNED_COMMIT from ponytail_runtime.py)",
    )
    args = parser.parse_args(argv)

    if args.check:
        problems: list[str] = []
        for plugin_dir in PLUGIN_DIRS:
            problems.extend(check(plugin_dir))
        if problems:
            print("vendored copy is out of date:")
            for problem in problems:
                print(f"  - {problem}")
            print("run: python3 octop/tools/sync_upstream.py")
            return 1
        print("vendored copy matches upstream: ok")
        return 0

    meta = upstream_meta(args.commit)
    for plugin_dir in PLUGIN_DIRS:
        vendor_root = sync(plugin_dir, args.commit)
        count = sum(1 for path in vendor_root.rglob("*") if path.is_file())
        print(f"synced {plugin_dir.name}: {count} files -> {vendor_root.relative_to(REPO_ROOT)}")
    print(f"upstream version={meta['version']} commit={meta['commit']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
